// Build the course kit's MyST plugin.
//
//   node build.mjs            dev build: assets referenced next to the bundle
//   node build.mjs --release  release build: assets referenced by exact-version CDN URL
//
// Output (dist/, published to npm):
//   nma.mjs            the MyST plugin (all features, one file)
//   assets/<feature>/  browser widgets and CSS
//   nma.yml            the config courses `extend:` (release only)
//   build-info.json    {mode, version}

import { build } from 'esbuild';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const dist = join(root, 'dist');
const release = process.argv.includes('--release');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const base = `https://cdn.jsdelivr.net/npm/@neuromatch/course-kit@${version}/dist/assets/`;

rmSync(dist, { recursive: true, force: true });
mkdirSync(join(dist, 'assets'), { recursive: true });

// The MyST plugin. Runs in Node inside `myst build`.
await build({
  entryPoints: [join(root, 'src', 'index.mjs')],
  outfile: join(dist, 'nma.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  logLevel: 'warning',
  banner: {
    js: [
      `// @neuromatch/course-kit ${version} MyST plugin (${release ? 'release' : 'dev'} build). GENERATED, do not edit.`,
      // Bundled CommonJS dependencies (yaml) call require() for Node built-ins.
      "import { createRequire as __nmaCreateRequire } from 'node:module';",
      'const require = __nmaCreateRequire(import.meta.url);',
    ].join('\n'),
  },
  define: {
    __NMA_BUNDLED__: 'true',
    __NMA_ASSET_BASE__: release ? JSON.stringify(base) : 'undefined',
  },
});

// Editable-cells widgets: CodeMirror etc. bundled into two browser modules.
await build({
  entryPoints: ['panel', 'runtime-widget'].map((n) => join(root, 'src', 'cells', 'src', `${n}.mjs`)),
  outdir: join(dist, 'assets', 'cells'),
  outExtension: { '.js': '.mjs' },
  bundle: true,
  format: 'esm',
  minify: true,
  logLevel: 'warning',
  banner: { js: '// GENERATED by npm run build in course-kit/js. Do not edit.' },
});

// Plain assets: copied as they are.
for (const feature of readdirSync(join(root, 'src'))) {
  const assets = join(root, 'src', feature, 'assets');
  if (existsSync(assets)) cpSync(assets, join(dist, 'assets', feature), { recursive: true });
}

if (release) {
  writeFileSync(join(dist, 'nma.yml'), readFileSync(join(root, 'nma.yml.tmpl'), 'utf8').replaceAll('@VERSION@', version));
}
writeFileSync(join(dist, 'build-info.json'), JSON.stringify({ mode: release ? 'release' : 'dev', version }, null, 2) + '\n');
console.log(`Built course kit ${version} (${release ? 'release' : 'dev'}) in dist/`);
